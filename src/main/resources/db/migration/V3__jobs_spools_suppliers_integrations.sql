-- V3: cola de trabajos, bobinas de filamento, proveedores y compras, presupuestos
-- públicos e integración con impresoras (telemetría).
-- Los enums se guardan como VARCHAR sin CHECK: agregar un valor no requiere migrar.

-- ── Bobinas de filamento ─────────────────────────────────────────────────────
CREATE TABLE filament_spools (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id     BIGINT           NOT NULL,
    material         VARCHAR(255)     NOT NULL,
    color            VARCHAR(255),
    brand            VARCHAR(255),
    initial_grams    DOUBLE PRECISION NOT NULL,
    remaining_grams  DOUBLE PRECISION NOT NULL,
    cost_per_kg      DOUBLE PRECISION NOT NULL,
    printer_id       BIGINT REFERENCES printers (id) ON DELETE SET NULL,
    low_alert_sent   BOOLEAN          NOT NULL DEFAULT FALSE,
    archived         BOOLEAN          NOT NULL DEFAULT FALSE,
    created_at       TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_spools_workspace ON filament_spools (workspace_id, archived);

-- ── Proveedores y órdenes de compra ──────────────────────────────────────────
CREATE TABLE suppliers (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT       NOT NULL,
    name         VARCHAR(255) NOT NULL,
    email        VARCHAR(255),
    phone        VARCHAR(255),
    website      VARCHAR(255),
    notes        TEXT,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_suppliers_workspace ON suppliers (workspace_id);

ALTER TABLE spare_parts ADD COLUMN supplier_id BIGINT REFERENCES suppliers (id) ON DELETE SET NULL;

CREATE TABLE purchase_orders (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id BIGINT       NOT NULL,
    supplier_id  BIGINT REFERENCES suppliers (id) ON DELETE SET NULL,
    number       VARCHAR(255),
    status       VARCHAR(255) NOT NULL,
    notes        TEXT,
    created_by   BIGINT REFERENCES users (id),
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT NOW(),
    sent_at      TIMESTAMP(6) WITH TIME ZONE,
    received_at  TIMESTAMP(6) WITH TIME ZONE
);
CREATE INDEX idx_purchase_orders_ws ON purchase_orders (workspace_id, created_at);

CREATE TABLE purchase_order_lines (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id BIGINT           NOT NULL REFERENCES purchase_orders (id) ON DELETE CASCADE,
    spare_part_id     BIGINT           NOT NULL REFERENCES spare_parts (id),
    quantity          INTEGER          NOT NULL,
    unit_cost         DOUBLE PRECISION
);
CREATE INDEX idx_po_lines_order ON purchase_order_lines (purchase_order_id);

-- ── Presupuestos: link público y bobina ──────────────────────────────────────
ALTER TABLE quotes ADD COLUMN public_token VARCHAR(255) UNIQUE;
ALTER TABLE quotes ADD COLUMN shared_at TIMESTAMP(6) WITH TIME ZONE;
ALTER TABLE quotes ADD COLUMN client_decision_at TIMESTAMP(6) WITH TIME ZONE;
ALTER TABLE quotes ADD COLUMN client_decision_note VARCHAR(1000);
ALTER TABLE quotes ADD COLUMN spool_id BIGINT REFERENCES filament_spools (id) ON DELETE SET NULL;

-- ── Cola de trabajos de impresión ────────────────────────────────────────────
CREATE TABLE print_jobs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id    BIGINT           NOT NULL,
    quote_id        BIGINT UNIQUE REFERENCES quotes (id) ON DELETE SET NULL,
    printer_id      BIGINT REFERENCES printers (id) ON DELETE SET NULL,
    spool_id        BIGINT REFERENCES filament_spools (id) ON DELETE SET NULL,
    title           VARCHAR(255)     NOT NULL,
    status          VARCHAR(255)     NOT NULL,
    priority        INTEGER          NOT NULL DEFAULT 0,
    units           INTEGER          NOT NULL DEFAULT 1,
    estimated_hours DOUBLE PRECISION NOT NULL DEFAULT 0,
    filament_grams  DOUBLE PRECISION NOT NULL DEFAULT 0,
    filament_type   VARCHAR(255),
    actual_hours    DOUBLE PRECISION,
    actual_grams    DOUBLE PRECISION,
    notes           TEXT,
    created_by      BIGINT REFERENCES users (id),
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT NOW(),
    started_at      TIMESTAMP(6) WITH TIME ZONE,
    finished_at     TIMESTAMP(6) WITH TIME ZONE
);
CREATE INDEX idx_print_jobs_ws_status ON print_jobs (workspace_id, status, priority);
CREATE INDEX idx_print_jobs_printer ON print_jobs (printer_id, status);

-- ── Integración con impresoras (agente local) ────────────────────────────────
CREATE TABLE printer_integrations (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    printer_id   BIGINT       NOT NULL UNIQUE REFERENCES printers (id) ON DELETE CASCADE,
    workspace_id BIGINT       NOT NULL,
    type         VARCHAR(255) NOT NULL,
    token_hash   VARCHAR(255) NOT NULL UNIQUE,
    token_hint   VARCHAR(255) NOT NULL,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT NOW(),
    last_seen_at TIMESTAMP(6) WITH TIME ZONE
);

-- Último estado reportado por impresora (una fila por impresora, se pisa).
CREATE TABLE printer_telemetry (
    printer_id        BIGINT PRIMARY KEY REFERENCES printers (id) ON DELETE CASCADE,
    workspace_id      BIGINT           NOT NULL,
    state             VARCHAR(255)     NOT NULL,
    progress          DOUBLE PRECISION,
    nozzle_temp       DOUBLE PRECISION,
    bed_temp          DOUBLE PRECISION,
    job_name          VARCHAR(255),
    remaining_seconds INTEGER,
    message           VARCHAR(255),
    updated_at        TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_printer_telemetry_ws ON printer_telemetry (workspace_id);
