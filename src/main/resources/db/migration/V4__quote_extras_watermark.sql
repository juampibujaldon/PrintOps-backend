-- V4: gastos extra por presupuesto (p. ej. "Rodamiento → $X"), marca de agua opcional y
-- columna de exportación del total de extras.

CREATE TABLE quote_extra_costs (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quote_id    BIGINT           NOT NULL REFERENCES quotes (id) ON DELETE CASCADE,
    description VARCHAR(255)     NOT NULL,
    amount      DOUBLE PRECISION NOT NULL,
    position    INTEGER          NOT NULL DEFAULT 0
);
CREATE INDEX idx_quote_extra_costs_quote ON quote_extra_costs (quote_id);

-- Total de gastos extra (se suman al precio a costo, sin margen ni descuento).
ALTER TABLE quotes ADD COLUMN extra_costs_total DOUBLE PRECISION NOT NULL DEFAULT 0;

-- Marca de agua "BORRADOR" en el PDF mientras el presupuesto es borrador (por defecto sí).
ALTER TABLE quotes ADD COLUMN draft_watermark BOOLEAN NOT NULL DEFAULT TRUE;

